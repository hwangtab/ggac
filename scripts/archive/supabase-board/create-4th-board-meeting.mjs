// 멱등 체크
const { data: existing } = await db
  .from('board_meetings')
  .select('id')
  .eq('title', TITLE)
  .eq('meeting_date', MEETING_DATE)
  .maybeSingle()
if (existing) {
  console.log(`이미 존재: ${TITLE} (${MEETING_DATE}) — 스킵`)
  process.exit(0)
}

const { data: meeting, error: mErr } = await db
  .from('board_meetings')
  .insert({
    title: TITLE,
    meeting_date: MEETING_DATE,
    location: '온라인',
    status: 'scheduled',
    created_at: CREATED_AT,
  })
  .select('id')
  .single()
if (mErr || !meeting) {
  console.error('회의 생성 실패:', mErr?.message)
  process.exit(1)
}

const rows = agendas.map((a, i) => ({
  meeting_id: meeting.id,
  title: a.title,
  content: a.content,
  sort_order: i,
  status: 'proposed',
}))
const { error: agErr } = await db.from('board_agendas').insert(rows)
if (agErr) {
  await db.from('board_meetings').delete().eq('id', meeting.id)
  console.error('안건 등록 실패(회의 롤백):', agErr.message)
  process.exit(1)
}

console.log(`생성: ${TITLE} (${MEETING_DATE} 21:00, 온라인) — 안건 ${rows.length}건 (proposed)`)
