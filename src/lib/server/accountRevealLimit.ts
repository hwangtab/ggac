/**
 * 계좌 열람 빈도 제한.
 *
 * 조합원 계좌(`/api/admin/members/[id]/account`)와 정산 입금 계좌
 * (`/api/admin/funding/campaigns/[id]/settlement?account=1`) 두 자리가 **하나의
 * 카운터를 나눠 쓴다.** 둘은 서로 다른 화면이지만 내보내는 것은 같은 것 —
 * 남의 계좌번호다. 따로 세면 한쪽을 다 쓴 뒤 다른 쪽으로 이어 걸으면 그만이라
 * 제한이 절반씩 두 개 있는 것이나 마찬가지가 된다.
 *
 * ## 왜 시간당 30번인가
 *
 * 조합원은 스무 명 남짓이다. 사무국이 한 회차 지급을 도는 일은 스무 번쯤
 * 열어 보는 일이고, 잘못 눌러 다시 열거나 화면을 새로 고치는 몫을 얹어도
 * 서른 번을 넘기 어렵다 — **실제로 돈을 보내는 사람은 이 벽에 닿지 않는다.**
 *
 * 반대로 전 조합원의 계좌를 긁어 가려는 쪽에서 보면, 한 시간에 서른 줄이
 * 상한이고 그 서른 줄은 **줄마다 활동 기록이 남는다**(누가·언제·누구의 것을).
 * 한도를 넘긴 요청은 429로 끊긴다. 스무 명뿐인 조합에서 이 숫자가 수집
 * 자체를 불가능하게 만들지는 못한다 — 그럴 수 있는 숫자는 사무국 업무도 함께
 * 막는다. 이 제한이 하는 일은 **한 세션이 조용히 훑고 지나가지 못하게** 만드는
 * 것이고, 남는 것은 기록과 429다.
 *
 * 창은 관리자 **한 사람** 기준이다. 기본 키 생성기는 전부 IP를 보는데, 사무국이
 * 한 사무실에서 일하면 그건 사람이 아니라 방 하나를 세는 셈이라 정상 업무가
 * 서로를 밀어낸다.
 */
export const ACCOUNT_REVEAL_RATE_LIMIT = {
  name: 'admin_account_reveal',
  windowMs: 60 * 60 * 1000,
  maxRequests: 30,
  message:
    '계좌 조회는 한 시간에 30번까지 됩니다. 지금은 더 볼 수 없으니 잠시 뒤에 다시 시도해 주세요. 지급할 건이 많아 계속 막히면 이사장에게 알려 주세요.',
} as const

/** 관리자 한 사람을 세는 키. IP가 아니라 사람을 센다(위 설명 참고). */
export function accountRevealRateLimitKey(adminUserId: string): string {
  return `rate_limit:admin-account-reveal:${adminUserId}`
}
